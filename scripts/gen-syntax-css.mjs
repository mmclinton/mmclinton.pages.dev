#!/usr/bin/env node
// Generate sass/_syntax.scss from Zola's giallo highlight output, scoping every
// rule under :root[data-theme="light"|"dark"] so code colors follow the manual
// theme toggle (the upstream files only support prefers-color-scheme).
//
// Run AFTER a `zola build` (which emits public/giallo-{light,dark}.css), then
// commit the result. Re-run only when markdown.highlighting themes change.

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const pub = path.join(root, "public");

function scope(css, prefix) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "") // strip comments
    .replace(/([^{}]+)\{([^}]*)\}/g, (_, selectors, body) => {
      const scoped = selectors
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean)
        .map((s) => `${prefix} ${s}`)
        .join(",\n");
      return `${scoped} {${body.trim() ? " " + body.trim() + " " : ""}}\n`;
    })
    .trim();
}

const read = (f) => fs.readFileSync(path.join(pub, f), "utf8");

const out = [
  "// GENERATED by scripts/gen-syntax-css.mjs — do not edit by hand.",
  "// Rerun after changing markdown.highlighting themes in config.toml.",
  "",
  scope(read("giallo-light.css"), ':root[data-theme="light"]'),
  "",
  scope(read("giallo-dark.css"), ':root[data-theme="dark"]'),
  "",
].join("\n");

fs.writeFileSync(path.join(root, "sass", "_syntax.scss"), out);
console.log("wrote sass/_syntax.scss");
